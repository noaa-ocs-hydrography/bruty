CREATE TABLE IF NOT EXISTS public.bruty_status
(
    status_id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    description TEXT,
    process_start_time TIMESTAMP,

    enc_request_pause BOOLEAN NOT NULL DEFAULT FALSE,
    enc_request_pause_at TIMESTAMP,

    is_paused BOOLEAN NOT NULL DEFAULT FALSE,
    is_paused_at TIMESTAMP,

    request_exit BOOLEAN NOT NULL DEFAULT FALSE,
    request_exit_at TIMESTAMP,

    tile_id BIGINT,
    res_id BIGINT,
    combine_id BIGINT,

    pid INTEGER,
    parent_pid INTEGER,

    progress REAL,
    host TEXT,

    CONSTRAINT progress_range
        CHECK (
            progress IS NULL
            OR progress BETWEEN 0 AND 100
        )
);

